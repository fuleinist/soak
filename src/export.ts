/**
 * CSV and HTML exports.
 */
import { VERDICT_LABELS, type ZoneAdvice } from "./advisor.js";
import { amountText } from "./report.js";
import { round1, round2 } from "./util.js";
import type { BalanceRow } from "./water.js";

export interface ZoneBalance {
  zoneId: string;
  zoneName: string;
  rows: BalanceRow[];
}

function csvField(value: string): string {
  if (/[",\n\r]/.test(value)) {
    return `"${value.replaceAll('"', '""')}"`;
  }
  return value;
}

export function balanceCsv(balances: ZoneBalance[]): string {
  const lines = ["date,zone_id,et0_mm,etc_mm,rain_mm,watering_mm,deficit_mm,depletion_pct"];
  for (const balance of balances) {
    for (const row of balance.rows) {
      lines.push(
        [
          row.date,
          csvField(balance.zoneId),
          round2(row.et0Mm),
          round2(row.etcMm),
          round2(row.rainMm),
          round2(row.wateringMm),
          round2(row.deficitMm),
          Math.round(row.depletion * 100),
        ].join(","),
      );
    }
  }
  return `${lines.join("\n")}\n`;
}

function escapeHtml(value: string): string {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

export interface HtmlInput {
  gardenName?: string;
  generatedAt: string;
  modelNote: string;
  advices: ZoneAdvice[];
  balances: ZoneBalance[];
}

export function htmlReport(input: HtmlInput): string {
  const name = input.gardenName ? escapeHtml(input.gardenName) : "Garden";

  const cards = input.advices
    .map((advice) => {
      const parts: string[] = [];
      parts.push(`<section class="card">`);
      parts.push(`<h2>${escapeHtml(advice.zoneName)} <span class="id">${escapeHtml(advice.zoneId)}</span></h2>`);
      parts.push(`<p><span class="badge ${advice.verdict}">${VERDICT_LABELS[advice.verdict]}</span></p>`);
      if (advice.verdict === "water") {
        parts.push(`<p class="amount">${amountText(advice.needMm, advice.litres, advice.minutes)}</p>`);
      }
      parts.push(`<p class="reason">${escapeHtml(advice.reason)}</p>`);
      parts.push(
        `<p class="stats">Deficit ${round1(advice.deficitMm)} mm · ${advice.depletionPct}% depleted · PAW ${round1(advice.pawMm)} mm · rain ahead ${round1(advice.rainSumMm)} mm</p>`,
      );
      parts.push(`</section>`);
      return parts.join("\n");
    })
    .join("\n");

  const tables = input.balances
    .map((balance) => {
      const rows = balance.rows
        .map((row) => {
          const pct = Math.min(100, Math.round(row.depletion * 100));
          return (
            `<tr><td>${row.date}</td><td>${round2(row.rainMm)}</td><td>${round2(row.et0Mm)}</td>` +
            `<td>${round2(row.wateringMm)}</td><td>${round2(row.deficitMm)}</td>` +
            `<td><span class="bar"><span style="width:${pct}%"></span></span> ${pct}%</td></tr>`
          );
        })
        .join("\n");
      return (
        `<h3>${escapeHtml(balance.zoneId)} · ${escapeHtml(balance.zoneName)}</h3>\n` +
        `<table>\n<thead><tr><th>Date</th><th>Rain mm</th><th>ET0 mm</th><th>Watering mm</th><th>Deficit mm</th><th>Depletion</th></tr></thead>\n` +
        `<tbody>\n${rows}\n</tbody>\n</table>`
      );
    })
    .join("\n");

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>soak — watering report</title>
<style>
body{font-family:system-ui,sans-serif;margin:2rem auto;max-width:60rem;padding:0 1rem;color:#1f2933}
h1{margin-bottom:.25rem}
.id{color:#7b8794;font-size:.8em;font-weight:400}
.badge{display:inline-block;padding:.15rem .6rem;border-radius:999px;color:#fff;font-weight:600;font-size:.8rem}
.badge.water{background:#b3261e}.badge.wait{background:#1a73e8}.badge.soon{background:#b26a00}.badge.ok{background:#1e7d32}
.card{border:1px solid #d9e2ec;border-radius:.5rem;padding:1rem;margin:1rem 0}
.amount{font-weight:600}
.reason{margin:.25rem 0}
.stats{color:#52606d;font-size:.9rem}
table{border-collapse:collapse;width:100%;font-size:.85rem;margin-bottom:2rem}
th,td{border-bottom:1px solid #e1e7ef;padding:.3rem .5rem;text-align:left}
.bar{display:inline-block;width:80px;height:.5rem;background:#e1e7ef;border-radius:999px;vertical-align:middle}
.bar span{display:block;height:100%;background:#1a73e8;border-radius:999px}
footer{color:#7b8794;font-size:.85rem}
</style>
</head>
<body>
<h1>${name} — watering report</h1>
<p class="stats">Generated ${escapeHtml(input.generatedAt)}. Source: Open-Meteo. Model: ${escapeHtml(input.modelNote)}.</p>
${cards}
${tables}
<footer>Generated by soak. 1 mm over 1 m² is 1 L.</footer>
</body>
</html>
`;
}